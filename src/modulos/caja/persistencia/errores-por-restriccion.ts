const delParDe = (tabla: string): Record<string, string> =>
  Object.fromEntries(
    Object.entries(ERRORES_DEL_PAR_DE_COBRO).map(([sufijo, error]) => [
      `${tabla}_${sufijo}`,
      error,
    ]),
  );

